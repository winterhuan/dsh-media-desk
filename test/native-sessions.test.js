test('冷启动先从原生入口继续同一 Session，llm-wiki 读取原 Wiki 和原生选定模型', { timeout: 180000 }, async t => {
  const recipes = {}
  const runtime = await nativeRuntime(t, { recipes })
  await Promise.all(['concepts', 'raw'].map(directory => mkdir(join(runtime.wiki, directory))))
  await writeFile(join(runtime.wiki, 'index.md'), '# Test Wiki\n\nContinuing native Sessions have durable tool history. See concepts/sessions.md.\n')
  await writeFile(join(runtime.wiki, 'SCHEMA.md'), 'Read-only queries cite sources and dates. Existing pages are not rewritten.\n')
  await writeFile(join(runtime.wiki, 'concepts', 'sessions.md'), '---\ntitle: Continuing Sessions\ndate: 2026-11-12\nconfidence: high\nsources: [raw/session-evidence.md]\n---\n\nNative Session history includes tool calls and their outcomes.\n')
  await writeFile(join(runtime.wiki, 'raw', 'session-evidence.md'), 'Source recorded 2026-11-12: the fixture observed 17 durable native tool events.\n')
  await writeFile(join(runtime.wiki, 'concepts', 'unrelated.md'), 'UNRELATED_WIKI_PAGE_MUST_NOT_BE_INJECTED\n')
  recipes.MD_FIXTURE_RESEARCH = { calls: [
    { name: 'skill', arguments: { name: 'llm-wiki' } },
    { name: 'read', arguments: { file_path: join(runtime.agents, 'skills', 'llm-wiki', 'references', 'query.md') } },
    { name: 'grep', arguments: { pattern: 'durable', path: 'index.md' } },
    { name: 'read', arguments: { file_path: 'concepts/sessions.md' } },
    { name: 'read', arguments: { file_path: 'raw/session-evidence.md' } },
    { name: 'bash', arguments: { description: 'Search the bound Wiki source', command: 'WIKI_PATH="$DSH_MEDIA_DESK_WIKI_PATH" sh -c \'rg -n "17 durable" "$WIKI_PATH/raw/session-evidence.md"\'', timeoutMs: 10000, run_in_background: false } },
  ], reply: 'The dated source records 17 durable tool events; this fixture observation does not guarantee current production behavior.' }
  await runtime.start()
  const opened = await runtime.host('sessions/open', { workId: 'seed_2' })
  assert.equal(opened.status, 200, JSON.stringify(opened.value))
  const association = opened.value.association
  const selected = await runtime.rpc('session/selectModel', { request: { sessionId: association.sessionId, provider: 'media-desk-fixture', model: 'native-second' } })
  assert.equal(selected.ok, true)
  await runtime.stop()
  const otherWiki = join(runtime.root, 'other-wiki')
  await mkdir(otherWiki)
  await writeFile(join(otherWiki, 'index.md'), 'WRONG_AMBIENT_WIKI\n')
  await runtime.start([], { WIKI_PATH: otherWiki })
  const requestId = await runtime.prompt(association.sessionId, 'Read-only MD_FIXTURE_RESEARCH: load llm-wiki and verify the source in the bound Wiki.')
  const finished = await runtime.turn(association.sessionId, requestId)
  assert.equal(finished.end.data.reason.kind, 'completed')
  const results = finished.events.filter(event => event.type === 'tool/result')
  assert.equal(results.length, 6)
  assert.ok(results.every(event => event.data.message.isError === false))
  const resultsText = JSON.stringify(results)
  assert.match(resultsText, /17 durable native tool events/)
  assert.match(resultsText, /2026-11-12/)
  assert.match(resultsText, /references\/query\.md/)
  assert.ok(!resultsText.includes(otherWiki))
  const requests = (await readFile(runtime.telemetryPath, 'utf8')).trim().split('\n').map(line => JSON.parse(line))
  assert.ok(requests.every(row => row.model === 'native-second'))
  const firstContext = JSON.stringify(requests[0].context)
  assert.ok(firstContext.includes(association.wikiRoot))
  assert.ok(!firstContext.includes('UNRELATED_WIKI_PAGE_MUST_NOT_BE_INJECTED'))
  assert.ok(!firstContext.includes('WRONG_AMBIENT_WIKI'))
  assert.ok(!firstContext.includes('You are a coding agent'))
  for (const name of ['read', 'write', 'edit', 'grep', 'glob', 'skill', 'ask_user_question']) assert.ok(requests[0].tools.includes(name), name)
  for (const name of ['subagent', 'antfarm_run', 'plugin_update', 'create_goal', 'schedule']) assert.ok(!requests[0].tools.includes(name), name)
  const restored = await runtime.host('sessions/open', { workId: 'seed_2' })
  assert.equal(restored.status, 200, JSON.stringify(restored.value))
  assert.equal(restored.value.association.sessionId, association.sessionId)
  assert.equal(restored.value.association.workspaceId, association.workspaceId)
  assert.equal(restored.value.association.wikiRoot, association.wikiRoot)
  assert.equal(restored.value.association.model.model, 'native-second')
  assert.equal((await readFile(join(otherWiki, 'index.md'), 'utf8')), 'WRONG_AMBIENT_WIKI\n')
})
