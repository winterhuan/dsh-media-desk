test('作品和全局助手分别复用已绑定的原生 Session 与 Wiki 工作区', { timeout: 180000 }, async t => {
  const runtime = await nativeRuntime(t)
  await runtime.start()
  const opened = await runtime.host('sessions/open', { workId: 'seed_2' })
  assert.equal(opened.status, 200)
  const work = opened.value.association
  assert.equal(work.status, 'bound')
  assert.equal(work.workId, 'seed_2')
  assert.equal(work.wikiRoot, await realpath(runtime.wiki))
  assert.equal(work.dshHome, await realpath(runtime.home))
  assert.equal(work.preset, 'media-desk-creative')
  assert.equal(typeof work.sessionId, 'string')
  assert.equal(typeof work.workspaceId, 'string')
  assert.deepEqual(work.model, { provider: 'media-desk-fixture', model: 'native-fixture' })
  const reopened = await runtime.host('sessions/open', { workId: 'seed_2' })
  assert.equal(reopened.status, 200, JSON.stringify(reopened.value))
  assert.equal(reopened.value.association.sessionId, work.sessionId)
  const global = await runtime.host('sessions/open', {})
  assert.equal(global.status, 200)
  assert.equal(global.value.association.workId, null)
  assert.notEqual(global.value.association.sessionId, work.sessionId)
  assert.equal(global.value.association.workspaceId, work.workspaceId)
  const state = await runtime.host('state')
  const listed = await runtime.rpc('session/list', { _request: {} })
  assert.equal(listed.ok, true)
  assert.equal(listed.value.items.find(row => row.sessionId === work.sessionId).projections?.values.title, state.value.state.items.find(row => row.id === 'seed_2').title)
  assert.equal(listed.value.items.find(row => row.sessionId === global.value.association.sessionId).projections?.values.title, 'Media Desk · 全局助手')
  const renamed = await runtime.rpc('session/rename', { request: { sessionId: work.sessionId, title: 'Saved native work title' } })
  assert.equal(renamed.ok, true)
  assert.equal((await runtime.host('sessions/open', { workId: 'seed_2' })).value.association.sessionId, work.sessionId)
  assert.equal((await runtime.rpc('session/list', { _request: {} })).value.items.find(row => row.sessionId === work.sessionId).projections?.values.title, 'Saved native work title')
  const page = await runtime.rpc('session/events', { request: { address: { kind: 'session', sessionId: work.sessionId } } })
  assert.equal(page.ok, true)
  assert.ok(page.value.records.some(record => record.type === 'event' && record.event.type === 'model/selection' && record.event.data.model === 'native-fixture'))
  const persisted = JSON.parse(await readFile(join(runtime.home, 'media-desk', 'sessions.json'), 'utf8'))
  assert.equal(persisted.associations.find(row => row.workId === 'seed_2').sessionId, work.sessionId)
})

test('缺失原生服务或 Wiki 时明确失败并保留工作台，不建立替代 Wiki 或 Session', { timeout: 180000 }, async t => {
  const runtime = await nativeRuntime(t)
  await runtime.start([{ id: 'session-controller', disabled: true }])
  const missingService = await runtime.host('sessions/open', { workId: 'seed_2' })
  assert.equal(missingService.status, 503)
  assert.equal(missingService.value.code, 'native/service-unavailable')
  assert.equal((await runtime.host('state')).status, 200)
  await assert.rejects(readFile(join(runtime.home, 'media-desk', 'sessions.json')), { code: 'ENOENT' })
  await runtime.stop()
  const missingWiki = join(runtime.root, 'missing-wiki')
  await runtime.start([], { WIKI_PATH: missingWiki })
  const failedWiki = await runtime.host('sessions/open', { workId: 'seed_2' })
  assert.equal(failedWiki.status, 503)
  assert.equal(failedWiki.value.code, 'wiki/unavailable')
  await assert.rejects(stat(missingWiki), { code: 'ENOENT' })
  const sessions = await runtime.rpc('session/list', { _request: {} })
  assert.equal(sessions.ok, true)
  assert.equal(sessions.value.items.length, 0)
  assert.equal((await runtime.host('state')).status, 200)
})

